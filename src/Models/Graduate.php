<?php

namespace Hazesoft\Refactor2\Models;

class Graduate extends Student
{
    protected function calculateGrade(int $score): string
    {
        return match (true) {
            $score >= 90 => 'A',
            $score >= 80 => 'B',
            $score >= 70 => 'C',
            $score >= 60 => 'D',
            default => 'F',
        };
    }
}
